WIDTH, HEIGHT, ADVANCE = 5, 7, 6

for _ch, _rows in FONT.items():
    assert len(_rows) == 7 and all(len(r) == 5 for r in _rows), _ch


def measure(text, scale=1):
    return max(0, len(text) * ADVANCE * scale - scale), HEIGHT * scale


def draw(px, text, x, y, colour, scale=1):
    """Stamp text onto a pixel-access object. Unknown chars render blank."""
    for i, ch in enumerate(text.upper()):
        rows = FONT.get(ch)
        if rows is None:
            continue
        ox = x + i * ADVANCE * scale
        for ry, row in enumerate(rows):
            for rx, cell in enumerate(row):
                if cell != "#":
                    continue
                for sy in range(scale):
                    for sx in range(scale):
                        px[ox + rx * scale + sx, y + ry * scale + sy] = colour
